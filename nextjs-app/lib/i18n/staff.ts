export type StaffKey = keyof typeof en;
const catalogs: Record<Locale, Record<StaffKey, string>> = { en, fr };

export function ts(locale: Locale, key: StaffKey, values?: Record<string, string | number>): string {
  let text = catalogs[locale]?.[key] ?? en[key] ?? key;
  if (values) for (const [k, v] of Object.entries(values)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

// Lookups for enumerations; unknown values fall through unchanged
export function label(locale: Locale, prefix: 'role' | 'ps' | 'as' | 'os' | 'ct' | 'm' | 'cat' | 'us' | 'vis' | 'slot' | 'ee' | 'funnel', value: string): string {
  const key = `${prefix}.${value}` as StaffKey;
  return catalogs[locale]?.[key] ?? value;
}

export const STAFF_LANG_KEY = 'ats_staff_lang';

export function readStaffLang(fallback: Locale = 'en'): Locale {
  try {
    const v = localStorage.getItem(STAFF_LANG_KEY);
    if (v === 'en' || v === 'fr') return v;
  } catch { /* ignore */ }
  if (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('fr')) return 'fr';
  return fallback;
}

export function writeStaffLang(locale: Locale): void {
  try { localStorage.setItem(STAFF_LANG_KEY, locale); } catch { /* ignore */ }
}

// Date/time in the viewer's language and the organization's zone, with abbreviation
export function fmt(locale: Locale, date: string | Date, timeZone: string): string {
  return new Intl.DateTimeFormat(locale === 'fr' ? 'fr-CA' : 'en-CA', { timeZone, dateStyle: 'medium', timeStyle: 'short', timeZoneName: 'short' } as Intl.DateTimeFormatOptions).format(new Date(date));
}

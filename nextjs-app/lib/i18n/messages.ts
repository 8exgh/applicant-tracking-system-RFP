export type MessageKey = keyof typeof en;
const catalogs: Record<Locale, Record<MessageKey, string>> = { en, fr };

export function t(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  let text = catalogs[locale]?.[key] ?? en[key] ?? key;
  if (values) for (const [k, v] of Object.entries(values)) text = text.split(`{${k}}`).join(String(v));
  return text;
}
